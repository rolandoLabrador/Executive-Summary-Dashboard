import { type Db } from 'mongodb';
import { type NormalizedClaim, type ReportModel } from '../models/report.types';
import { AiAnalystService, type PortfolioSummaryData } from './ai_analyst.service';

export class SnapshotService {
  constructor(
    private readonly db: Db,
    private readonly collectionName: string = 'executive_report_snapshots',
  ) {}

  public async saveSnapshot(model: ReportModel, aiSummaryText?: string): Promise<void> {
    const year = model.asOfDate.getFullYear();
    const month = String(model.asOfDate.getMonth() + 1).padStart(2, '0');
    const day = String(model.asOfDate.getDate()).padStart(2, '0');
    const asOfDateStr = `${year}-${month}-${day}`;

    // If aiSummaryText is not provided, generate or fetch it using AiAnalystService
    let summary = aiSummaryText;
    if (!summary) {
      try {
        const aiService = new AiAnalystService();
        const topAgentRisk = [...model.itdAgents]
          .filter((a) => a.contractsWritten >= 50)
          .sort((a, b) => (b.earnedLossRatio ?? 0) - (a.earnedLossRatio ?? 0))[0];
        const topLossCodeEntry = model.lossCodeDashboard?.rows?.[0];

        const portfolioData: PortfolioSummaryData = {
          companyName: 'OmniShield Protection Plans',
          asOfDate: model.asOfDate,
          rollingContracts: model.rolling12.current.contractsWritten,
          rollingReserve: model.rolling12.current.netReserve,
          rollingEarnedReserve: model.rolling12.current.earnedReserve,
          rollingClaims: model.rolling12.current.claimsPaid,
          rollingLossRatio: model.rolling12.current.earnedLossRatio ?? 0,
          rollingUnderwritingProfit: model.rolling12.current.underwritingProfit,
          priorRollingContracts: model.rolling12.prior.contractsWritten,
          priorRollingLossRatio: model.rolling12.prior.earnedLossRatio ?? 0,
          itdContracts: model.inceptionToDate.values.contractsWritten,
          itdEarnedReserve: model.inceptionToDate.values.earnedReserve,
          itdClaims: model.inceptionToDate.values.claimsPaid,
          itdLossRatio: model.inceptionToDate.values.earnedLossRatio ?? 0,
          itdUnderwritingProfit: model.inceptionToDate.values.underwritingProfit,
          topAgentRisk: topAgentRisk
            ? {
                name: topAgentRisk.displayName || topAgentRisk.name,
                lossRatio: topAgentRisk.earnedLossRatio ?? 0,
                paidClaims: topAgentRisk.claimsPaid,
              }
            : undefined,
          topLossCode: topLossCodeEntry
            ? {
                code: topLossCodeEntry.code,
                description: topLossCodeEntry.description,
                amount: topLossCodeEntry.rolling12Paid,
              }
            : undefined,
        };
        summary = await aiService.generatePortfolioOverview(portfolioData);
      } catch (err) {
        console.warn('[SnapshotService] Failed to generate AI summary, using default:', err);
        summary = 'Underwriting portfolio analysis generated by AI Actuary.';
      }
    }

    // Compute Top 20 Worst Dealers by ITD Earned Loss Ratio (>= 5 contracts written)
    const worstDealers = [...model.itdDealers]
      .filter(
        (d) =>
          d.earnedReserve > 0 &&
          d.claimsPaid > 0 &&
          (d.contractsWritten >= 5 || d.activeContracts >= 5),
      )
      .sort((a, b) => (b.earnedLossRatio || 0) - (a.earnedLossRatio || 0))
      .slice(0, 20)
      .map((d, index) => ({
        rank: index + 1,
        dealerName: d.displayName || d.name,
        activeContracts: d.activeContracts,
        contractsWritten: d.contractsWritten,
        netWrittenReserve: d.netReserve,
        earnedReserve: d.earnedReserve,
        claimsPaid: d.claimsPaid,
        underwritingProfit: d.underwritingProfit,
        earnedLossRatio: d.earnedLossRatio || 0,
        claimFrequency:
          d.claimFrequency ?? (d.contractsWritten > 0 ? d.claimCount / d.contractsWritten : 0),
        claimSeverity: d.claimSeverity ?? (d.claimCount > 0 ? d.claimsPaid / d.claimCount : 0),
        percentEarned: d.percentEarned ?? (d.netReserve > 0 ? d.earnedReserve / d.netReserve : 0),
      }));

    // Build lean, aggregated JSON payload (< 200KB)
    const payload = {
      asOfDate: model.asOfDate,
      asOfDateStr,
      generatedAt: new Date(),
      companyName: 'OmniShield Protection Plans',
      currentMonth: model.currentMonth,
      yearToDate: model.yearToDate,
      rolling12: model.rolling12,
      priorCalendarYear: model.priorCalendarYear,
      inceptionToDate: model.inceptionToDate,
      monthlyTrends: model.monthly.slice(-24).map((m) => ({
        ...m,
        periodLabel: m.period,
      })),
      worstDealers,
      topDealers: model.dealers.slice(0, 20),
      allDealers: model.dealers,
      agents: model.agents.slice(0, 50),
      allAgents: model.agents,
      products: model.products,
      lossCodeDashboard: {
        currentMonth: model.lossCodeDashboard.currentMonth,
        yearToDate: model.lossCodeDashboard.yearToDate,
        rolling12: model.lossCodeDashboard.rolling12,
        topVehicleMakes: model.lossCodeDashboard.topVehicleMakes.slice(0, 10),
        rows: model.lossCodeDashboard.rows.filter((r) => (r.rolling12PaidShare || 0) >= 0.02),
      },
      aiPortfolioSummary: {
        executiveSummaryText: summary || 'Underwriting portfolio analysis generated by AI Actuary.',
        generatedAt: new Date(),
      },
      metadata: {
        sourceCounts: model.sourceCounts,
        dataQualityIssueCount: model.dataQualityIssues.length,
      },
    };

    const collection = this.db.collection(this.collectionName);
    await collection.createIndex({ asOfDateStr: 1 }, { unique: true });
    await collection.updateOne({ asOfDateStr }, { $set: payload }, { upsert: true });

    console.log(
      `✅ Executive snapshot successfully upserted to MongoDB [${this.collectionName}] for asOf: ${asOfDateStr}`,
    );

    // Save detailed drilldown debug snapshots for all dealers and agents
    await this.saveDebugSnapshots(model, asOfDateStr);
  }

  /**
   * Persists pre-aggregated drilldown documents for every dealer and agent into
   * dedicated, indexed collections (dealer_debug_snapshots and agent_debug_snapshots).
   * This gives the UI sub-second (< 50ms) debug inspections for any dealer or agent.
   */
  private async saveDebugSnapshots(model: ReportModel, asOfDateStr: string): Promise<void> {
    const dealerColl = this.db.collection('dealer_debug_snapshots');
    const agentColl = this.db.collection('agent_debug_snapshots');

    await dealerColl.createIndex({ dealerName: 1, asOfDateStr: 1 }, { unique: true });
    await agentColl.createIndex({ agentName: 1, asOfDateStr: 1 }, { unique: true });

    // Maps for fast O(1) dimension lookups across time horizons
    const itdDealerMap = new Map(model.itdDealers.map((d) => [d.name, d]));
    const rollingDealerMap = new Map(model.dealers.map((d) => [d.name, d]));
    const ytdDealerMap = new Map(model.ytdDealers.map((d) => [d.name, d]));
    const monthlyDealerMap = new Map(model.monthlyDealers.map((d) => [d.name, d]));

    // Group claims by dealer for instant loss-code drilldowns
    const claimsByDealer = new Map<string, NormalizedClaim[]>();
    for (const c of model.claims) {
      const dName = c.dealerName || c.dealer;
      if (!claimsByDealer.has(dName)) {
        claimsByDealer.set(dName, []);
      }
      claimsByDealer.get(dName)!.push(c);
    }

    // Set of all unique dealer names across all periods
    const allDealerNames = new Set([
      ...itdDealerMap.keys(),
      ...rollingDealerMap.keys(),
      ...ytdDealerMap.keys(),
      ...monthlyDealerMap.keys(),
    ]);

    const dealerOps = [];
    for (const dealerName of allDealerNames) {
      const itd = itdDealerMap.get(dealerName) ?? null;
      const rolling = rollingDealerMap.get(dealerName) ?? null;
      const ytd = ytdDealerMap.get(dealerName) ?? null;
      const month = monthlyDealerMap.get(dealerName) ?? null;
      const displayName = itd?.displayName || rolling?.displayName || dealerName;
      const relatedAgents = itd?.relatedAgents || rolling?.relatedAgents || [];

      // Calculate top loss codes for this dealer
      const dClaims = claimsByDealer.get(dealerName) || [];
      const lossMap = new Map<
        string,
        { code: string; description: string; claimCount: number; totalPaid: number }
      >();
      for (const cl of dClaims) {
        const code = cl.lossCode || 'UNMAPPED';
        const desc = cl.lossCodeDescription || 'Description unavailable';
        const entry = lossMap.get(code) || {
          code,
          description: desc,
          claimCount: 0,
          totalPaid: 0,
        };
        entry.claimCount += 1;
        entry.totalPaid += cl.paidAmount;
        lossMap.set(code, entry);
      }
      const topLossCodes = Array.from(lossMap.values())
        .sort((a, b) => b.totalPaid - a.totalPaid)
        .slice(0, 15);

      const doc = {
        dealerName,
        displayName,
        asOfDateStr,
        generatedAt: new Date(),
        relatedAgents,
        currentMonth: month,
        yearToDate: ytd,
        rolling12: rolling,
        inceptionToDate: itd,
        topLossCodes,
      };

      dealerOps.push({
        updateOne: {
          filter: { dealerName, asOfDateStr },
          update: { $set: doc },
          upsert: true,
        },
      });
    }

    if (dealerOps.length > 0) {
      await dealerColl.bulkWrite(dealerOps, { ordered: false });
      console.log(
        `✅ Upserted ${dealerOps.length} dealer debug snapshots to [dealer_debug_snapshots]`,
      );
    }

    // Agents
    const itdAgentMap = new Map(model.itdAgents.map((a) => [a.name, a]));
    const rollingAgentMap = new Map(model.agents.map((a) => [a.name, a]));
    const ytdAgentMap = new Map(model.ytdAgents.map((a) => [a.name, a]));
    const monthlyAgentMap = new Map(model.monthlyAgents.map((a) => [a.name, a]));

    const allAgentNames = new Set([
      ...itdAgentMap.keys(),
      ...rollingAgentMap.keys(),
      ...ytdAgentMap.keys(),
      ...monthlyAgentMap.keys(),
    ]);

    const agentOps = [];
    for (const agentName of allAgentNames) {
      const itd = itdAgentMap.get(agentName) ?? null;
      const rolling = rollingAgentMap.get(agentName) ?? null;
      const ytd = ytdAgentMap.get(agentName) ?? null;
      const month = monthlyAgentMap.get(agentName) ?? null;
      const displayName = itd?.displayName || rolling?.displayName || agentName;
      const relatedDealers = itd?.relatedDealers || rolling?.relatedDealers || [];

      // Sub-dealers breakdown under this agent
      const dealersBreakdown = relatedDealers
        .map((dName) => {
          const dItd = itdDealerMap.get(dName);
          return {
            dealerName: dName,
            displayName: dItd?.displayName || dName,
            contractsWritten: dItd?.contractsWritten ?? 0,
            activeContracts: dItd?.activeContracts ?? 0,
            claimsPaid: dItd?.claimsPaid ?? 0,
            earnedReserve: dItd?.earnedReserve ?? 0,
            earnedLossRatio: dItd?.earnedLossRatio ?? null,
          };
        })
        .sort((a, b) => (b.claimsPaid || 0) - (a.claimsPaid || 0));

      const doc = {
        agentName,
        displayName,
        asOfDateStr,
        generatedAt: new Date(),
        relatedDealers,
        currentMonth: month,
        yearToDate: ytd,
        rolling12: rolling,
        inceptionToDate: itd,
        dealersBreakdown,
      };

      agentOps.push({
        updateOne: {
          filter: { agentName, asOfDateStr },
          update: { $set: doc },
          upsert: true,
        },
      });
    }

    if (agentOps.length > 0) {
      await agentColl.bulkWrite(agentOps, { ordered: false });
      console.log(
        `✅ Upserted ${agentOps.length} agent debug snapshots to [agent_debug_snapshots]`,
      );
    }
  }
}
