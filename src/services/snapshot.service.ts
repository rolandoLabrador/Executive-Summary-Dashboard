import { type Db } from 'mongodb';
import { type ReportModel } from '../models/report.types';
import { AiAnalystService, type PortfolioSummaryData } from './ai_analyst.service';

export class SnapshotService {
  constructor(
    private readonly db: Db,
    private readonly collectionName: string = 'executive_report_snapshots',
  ) {}

  public async saveSnapshot(model: ReportModel, aiSummaryText?: string): Promise<void> {
    const year = model.asOfDate.getFullYear();
    const month = String(model.asOfDate.getMonth() + 1).padStart(2, '0');
    const day = String(model.asOfDate.getDate()).padStart(2, '0');
    const asOfDateStr = `${year}-${month}-${day}`;

    // If aiSummaryText is not provided, generate or fetch it using AiAnalystService
    let summary = aiSummaryText;
    if (!summary) {
      try {
        const aiService = new AiAnalystService();
        const topAgentRisk = [...model.itdAgents]
          .filter((a) => a.contractsWritten >= 50)
          .sort((a, b) => (b.earnedLossRatio ?? 0) - (a.earnedLossRatio ?? 0))[0];
        const topLossCodeEntry = model.lossCodeDashboard?.rows?.[0];

        const portfolioData: PortfolioSummaryData = {
          companyName: 'OmniShield Protection Plans',
          asOfDate: model.asOfDate,
          rollingContracts: model.rolling12.current.contractsWritten,
          rollingReserve: model.rolling12.current.netReserve,
          rollingEarnedReserve: model.rolling12.current.earnedReserve,
          rollingClaims: model.rolling12.current.claimsPaid,
          rollingLossRatio: model.rolling12.current.earnedLossRatio ?? 0,
          rollingUnderwritingProfit: model.rolling12.current.underwritingProfit,
          priorRollingContracts: model.rolling12.prior.contractsWritten,
          priorRollingLossRatio: model.rolling12.prior.earnedLossRatio ?? 0,
          itdContracts: model.inceptionToDate.values.contractsWritten,
          itdEarnedReserve: model.inceptionToDate.values.earnedReserve,
          itdClaims: model.inceptionToDate.values.claimsPaid,
          itdLossRatio: model.inceptionToDate.values.earnedLossRatio ?? 0,
          itdUnderwritingProfit: model.inceptionToDate.values.underwritingProfit,
          topAgentRisk: topAgentRisk
            ? {
                name: topAgentRisk.displayName || topAgentRisk.name,
                lossRatio: topAgentRisk.earnedLossRatio ?? 0,
                paidClaims: topAgentRisk.claimsPaid,
              }
            : undefined,
          topLossCode: topLossCodeEntry
            ? {
                code: topLossCodeEntry.code,
                description: topLossCodeEntry.description,
                amount: topLossCodeEntry.rolling12Paid,
              }
            : undefined,
        };
        summary = await aiService.generatePortfolioOverview(portfolioData);
      } catch (err) {
        console.warn('[SnapshotService] Failed to generate AI summary, using default:', err);
        summary = 'Underwriting portfolio analysis generated by AI Actuary.';
      }
    }

    // Compute Top 20 Worst Dealers by ITD Earned Loss Ratio (>= 5 contracts written)
    const worstDealers = [...model.itdDealers]
      .filter(
        (d) =>
          d.earnedReserve > 0 &&
          d.claimsPaid > 0 &&
          (d.contractsWritten >= 5 || d.activeContracts >= 5),
      )
      .sort((a, b) => (b.earnedLossRatio || 0) - (a.earnedLossRatio || 0))
      .slice(0, 20)
      .map((d, index) => ({
        rank: index + 1,
        dealerName: d.displayName || d.name,
        activeContracts: d.activeContracts,
        contractsWritten: d.contractsWritten,
        netWrittenReserve: d.netReserve,
        earnedReserve: d.earnedReserve,
        claimsPaid: d.claimsPaid,
        underwritingProfit: d.underwritingProfit,
        earnedLossRatio: d.earnedLossRatio || 0,
        claimFrequency:
          d.claimFrequency ?? (d.contractsWritten > 0 ? d.claimCount / d.contractsWritten : 0),
        claimSeverity: d.claimSeverity ?? (d.claimCount > 0 ? d.claimsPaid / d.claimCount : 0),
        percentEarned: d.percentEarned ?? (d.netReserve > 0 ? d.earnedReserve / d.netReserve : 0),
      }));

    // Build lean, aggregated JSON payload (< 200KB)
    const payload = {
      asOfDate: model.asOfDate,
      asOfDateStr,
      generatedAt: new Date(),
      companyName: 'OmniShield Protection Plans',
      currentMonth: model.currentMonth,
      yearToDate: model.yearToDate,
      rolling12: model.rolling12,
      priorCalendarYear: model.priorCalendarYear,
      inceptionToDate: model.inceptionToDate,
      monthlyTrends: model.monthly.slice(-24).map((m) => ({
        ...m,
        periodLabel: m.period,
      })),
      worstDealers,
      topDealers: model.dealers.slice(0, 20),
      agents: model.agents.slice(0, 50),
      products: model.products,
      lossCodeDashboard: {
        currentMonth: model.lossCodeDashboard.currentMonth,
        yearToDate: model.lossCodeDashboard.yearToDate,
        rolling12: model.lossCodeDashboard.rolling12,
        topVehicleMakes: model.lossCodeDashboard.topVehicleMakes.slice(0, 10),
        rows: model.lossCodeDashboard.rows.filter((r) => (r.rolling12PaidShare || 0) >= 0.02),
      },
      aiPortfolioSummary: {
        executiveSummaryText: summary || 'Underwriting portfolio analysis generated by AI Actuary.',
        generatedAt: new Date(),
      },
      metadata: {
        sourceCounts: model.sourceCounts,
        dataQualityIssueCount: model.dataQualityIssues.length,
      },
    };

    const collection = this.db.collection(this.collectionName);
    await collection.createIndex({ asOfDateStr: 1 }, { unique: true });
    await collection.updateOne({ asOfDateStr }, { $set: payload }, { upsert: true });

    console.log(
      `✅ Executive snapshot successfully upserted to MongoDB [${this.collectionName}] for asOf: ${asOfDateStr}`,
    );
  }
}
